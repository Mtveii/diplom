function isPaucal(n: number): boolean {
  const mod10 = n % 10
  const mod100 = n % 100
  return mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)
}

function pluralMinute(minutes: number): string {
  const n = Math.max(1, minutes)
  if (n === 1) return `před ${n} minutou`
  return `před ${n} minutami`
}

function pluralHour(hours: number): string {
  if (hours === 1) return `před ${hours} hodinou`
  return `před ${hours} hodinami`
}

function pluralDay(days: number): string {
  if (days === 1) return `před ${days} dnem`
  return `před ${days} dny`
}

function pluralPlayers(count: number): string {
  if (count === 1) return `${count} hráč`
  if (isPaucal(count)) return `${count} hráči`
  return `${count} hráčů`
}

