function pluralMinute(minutes: number): string {
  const n = Math.max(1, minutes)
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return `${n} хвилину тому`
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return `${n} хвилини тому`
  return `${n} хвилин тому`
}

function pluralHour(hours: number): string {
  const mod10 = hours % 10
  const mod100 = hours % 100
  if (mod10 === 1 && mod100 !== 11) return `${hours} годину тому`
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return `${hours} години тому`
  return `${hours} годин тому`
}

function pluralDay(days: number): string {
  const mod10 = days % 10
  const mod100 = days % 100
  if (mod10 === 1 && mod100 !== 11) return `${days} день тому`
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return `${days} дні тому`
  return `${days} днів тому`
}

function pluralPlayers(count: number): string {
  const mod10 = count % 10
  const mod100 = count % 100
  if (mod10 === 1 && mod100 !== 11) return `${count} гравець`
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return `${count} гравці`
  return `${count} гравців`
}

