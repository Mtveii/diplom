function isPaucal(n: number): boolean {
  const mod10 = n % 10
  const mod100 = n % 100
  return mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)
}

function pluralMinute(minutes: number): string {
  const n = Math.max(1, minutes)
  if (n === 1) return `${n} minutę temu`
  if (isPaucal(n)) return `${n} minuty temu`
  return `${n} minut temu`
}

function pluralHour(hours: number): string {
  if (hours === 1) return `${hours} godzinę temu`
  if (isPaucal(hours)) return `${hours} godziny temu`
  return `${hours} godzin temu`
}

function pluralDay(days: number): string {
  if (days === 1) return `${days} dzień temu`
  return `${days} dni temu`
}

function pluralPlayers(count: number): string {
  if (count === 1) return `${count} gracz`
  return `${count} graczy`
}

